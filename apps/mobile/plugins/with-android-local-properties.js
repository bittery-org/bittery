const { withDangerousMod } = require("expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

/**
 * Expo config plugin that creates android/local.properties with the SDK path.
 * This runs during prebuild and ensures the file exists even after --clean.
 */
function withAndroidLocalProperties(config) {
	return withDangerousMod(config, [
		"android",
		async (config) => {
			const androidDir = path.join(config.modRequest.platformProjectRoot);
			const localPropertiesPath = path.join(androidDir, "local.properties");

			// Try to get SDK path from environment variables
			const sdkPath =
				process.env.ANDROID_HOME ||
				process.env.ANDROID_SDK_ROOT ||
				path.join(process.env.HOME, "Library/Android/sdk");

			// Check if the SDK path exists
			if (!fs.existsSync(sdkPath)) {
				console.warn(
					`⚠️  Android SDK not found at ${sdkPath}. Please set ANDROID_HOME environment variable.`,
				);
			}

			const content = `# Generated by with-android-local-properties plugin
sdk.dir=${sdkPath}
`;

			fs.writeFileSync(localPropertiesPath, content);
			console.log(`✓ Created local.properties with sdk.dir=${sdkPath}`);

			return config;
		},
	]);
}

module.exports = withAndroidLocalProperties;
